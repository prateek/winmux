import Foundation

public let columnInitManagedBlockBegin = "# BEGIN WINMUX COLUMN INIT MANAGED BLOCK"
public let columnInitManagedBlockEnd = "# END WINMUX COLUMN INIT MANAGED BLOCK"
private let legacyColumnInitManagedBlockBegin = "# BEGIN WINMUX ZONE INIT MANAGED BLOCK"
private let legacyColumnInitManagedBlockEnd = "# END WINMUX ZONE INIT MANAGED BLOCK"

public enum ColumnInitConfigEditStatus: Equatable, Sendable {
    case appended
    case replaced
    case unchanged
}

public struct ColumnInitConfigEditResult: Equatable, Sendable {
    public let updatedText: String
    public let status: ColumnInitConfigEditStatus

    public init(updatedText: String, status: ColumnInitConfigEditStatus) {
        self.updatedText = updatedText
        self.status = status
    }
}

public struct ColumnInitConfigValidation: Equatable, Sendable {
    public let hasActiveColumns: Bool

    public init(hasActiveColumns: Bool) {
        self.hasActiveColumns = hasActiveColumns
    }
}

public struct ColumnInitColumnDefinition: Equatable, Sendable {
    public let id: String
    public let name: String?
    public let width: Double

    public init(id: String, name: String?, width: Double) {
        self.id = id
        self.name = name
        self.width = width
    }
}

public struct ColumnInitPresetDefinition: Equatable, Sendable {
    public let defaultColumnId: String
    public let columns: [ColumnInitColumnDefinition]

    public init(defaultColumnId: String, columns: [ColumnInitColumnDefinition]) {
        self.defaultColumnId = defaultColumnId
        self.columns = columns
    }
}

