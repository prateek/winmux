import Foundation

public let zoneInitManagedBlockBegin = "# BEGIN WINMUX ZONE INIT MANAGED BLOCK"
public let zoneInitManagedBlockEnd = "# END WINMUX ZONE INIT MANAGED BLOCK"

public enum ZoneInitConfigEditStatus: Equatable, Sendable {
    case appended
    case replaced
    case unchanged
}

public struct ZoneInitConfigEditResult: Equatable, Sendable {
    public let updatedText: String
    public let status: ZoneInitConfigEditStatus

    public init(updatedText: String, status: ZoneInitConfigEditStatus) {
        self.updatedText = updatedText
        self.status = status
    }
}

public struct ZoneInitConfigValidation: Equatable, Sendable {
    public let hasActiveZones: Bool

    public init(hasActiveZones: Bool) {
        self.hasActiveZones = hasActiveZones
    }
}

public struct ZoneInitColumnDefinition: Equatable, Sendable {
    public let id: String
    public let name: String?
    public let width: Double

    public init(id: String, name: String?, width: Double) {
        self.id = id
        self.name = name
        self.width = width
    }
}

public struct ZoneInitPresetDefinition: Equatable, Sendable {
    public let defaultZoneId: String
    public let columns: [ZoneInitColumnDefinition]

    public init(defaultZoneId: String, columns: [ZoneInitColumnDefinition]) {
        self.defaultZoneId = defaultZoneId
        self.columns = columns
    }
}

public func zoneInitPresetDefinition(_ preset: ZoneInitPreset) -> ZoneInitPresetDefinition {
    switch preset {
        case .balanced:
            ZoneInitPresetDefinition(defaultZoneId: "main", columns: [
