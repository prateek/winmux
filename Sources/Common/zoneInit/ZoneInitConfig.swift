        case .commsOpen:
            ZoneInitPresetDefinition(defaultZoneId: "main", columns: [
                ZoneInitColumnDefinition(id: "left", name: "Reference", width: 0.20),
                ZoneInitColumnDefinition(id: "main", name: "Work", width: 0.55),
