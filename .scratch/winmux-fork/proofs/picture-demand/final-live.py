import json, time
import run
app=run.start('branch','final-live')
run.prompts()
phases={'pid':app.pid}
(run.OUT/'final-live-query.json').unlink(missing_ok=True)
run.cli('agent','query','--path',str(run.OUT/'final-live-query.json'))
time.sleep(3)
run.focus_all(['Window 01','Window 02','Window 03'])
time.sleep(5)
phases['gridStart']=time.time()
run.cli('lens','windows')
time.sleep(6)
run.screenshot('final-three-grid')
(run.OUT/'final-three-trace.json').write_text(run.cli('debug-lens-trace','--json','--last','1'))
phases['gridEnd']=time.time()
run.keys('tap:escape','wait:1')
time.sleep(3)
run.call([run.HOME/'proof94/small-window'])
time.sleep(3)
(run.OUT/'native-cap-query.json').unlink(missing_ok=True)
run.cli('agent','query','--path',str(run.OUT/'native-cap-query.json'))
time.sleep(3)
run.focus_all(['Window 01','Window 02','Window 03'])
time.sleep(5)
run.call([run.HOME/'proof94/small-window','--inspect'])
windows=json.loads(run.cli('list-windows','--all','--json'))
target=next(w['window-id'] for w in windows if w['window-title']=='Window 01')
phases['stripStart']=time.time()
run.cli('lens','recent')
time.sleep(6)
trace=json.loads(run.cli('debug-lens-trace','--json','--last','1'))
for _ in range(3):
    if trace[0]['session']['selectedId']==target: break
    run.keys('tap:left','wait:1')
    time.sleep(1)
    trace=json.loads(run.cli('debug-lens-trace','--json','--last','1'))
assert trace[0]['session']['selectedId']==target,trace
run.screenshot('strip-native-cap')
(run.OUT/'strip-native-cap-trace.json').write_text(json.dumps(trace,indent=2))
phases['stripEnd']=time.time()
run.keys('tap:escape','wait:1')
time.sleep(3)
run.screenshot('strip-native-cap-closed')
(run.OUT/'final-live-end.txt').write_text(run.cli('debug-lens-trace','--last','1')+'\n'+run.cli('list-windows','--all')+'\n'+run.cli('list-workspaces','--focused'))
(run.OUT/'final-live-phases.json').write_text(json.dumps(phases,indent=2))
run.stop()
