"""Generate build provenance; vm sync uses the same dirty-source rule on the host."""
from pathlib import Path
import re
import subprocess
import sys

GENERATED = ('Sources/Common/versionGenerated.swift', 'Sources/Common/gitHashGenerated.swift')


def git_commit(root):
    def git(*args):
        return subprocess.check_output(['git', '-C', str(root), *args], stderr=subprocess.DEVNULL, text=True).strip()

    try:
        head = git('rev-parse', '--verify', 'HEAD')
        changes = git('status', '--porcelain', '--untracked-files=all', '--', '.',
                      *(f':(exclude){path}' for path in GENERATED))
        return head + ('-dirty' if changes else '')
    except (subprocess.CalledProcessError, FileNotFoundError):
        return 'unknown'


def generate(root):
    marker = root / '.source-commit'
    commit = marker.read_text().strip() if marker.exists() else git_commit(root)
    if not re.fullmatch(r'[0-9a-f]{40}(-dirty)?', commit):
        commit = 'unknown'
    short = commit if commit == 'unknown' else commit[:8] + ('-dirty' if commit.endswith('-dirty') else '')
    (root / GENERATED[1]).write_text(
        '// FILE IS GENERATED BY Makefile\n'
        f'public let gitHash = "{commit}"\n'
        f'public let gitShortHash = "{short}"\n')


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == '--git-only':
        print(git_commit(Path(sys.argv[2])))
    elif len(sys.argv) == 1:
        generate(Path.cwd())
    else:
        sys.exit('usage: source_commit.py [--git-only <worktree>]')
