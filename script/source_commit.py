"""Generate build provenance; vm sync uses the same dirty-source rule on the host."""
from pathlib import Path
import re
import subprocess
import sys

GENERATED = ('Sources/Common/versionGenerated.swift', 'Sources/Common/gitHashGenerated.swift')
COMMIT = re.compile(r'(?:[0-9a-f]{40}|[0-9a-f]{64})(?:-dirty)?')


def git_commit(root):
    def git(*args):
        return subprocess.check_output(['git', '-C', str(root), *args], stderr=subprocess.DEVNULL, text=True).strip()

    try:
        # A tree nested in another repository is not that repository's source.
        if git('rev-parse', '--show-prefix'):
            return 'unknown'
        head = git('rev-parse', '--verify', 'HEAD')
        changes = git('status', '--porcelain', '--untracked-files=all', '--', '.',
                      *(f':(exclude){path}' for path in GENERATED))
        return head + ('-dirty' if changes else '')
    except (subprocess.CalledProcessError, FileNotFoundError):
        return 'unknown'


def generate(root, version):
    write_if_changed(root / GENERATED[0],
                     '// FILE IS GENERATED BY Makefile\n'
                     f'public let winMuxAppVersion = "{version}"\n')
    marker = root / '.source-commit'
    if marker.exists():
        commit = marker.read_text().strip()
        # The guest's repository holds the synced tree as its sync commit: an edit made in the
        # guest after the sync makes it dirty.
        if COMMIT.fullmatch(commit) and not commit.endswith('-dirty') and git_commit(root).endswith('-dirty'):
            commit += '-dirty'
    else:
        commit = git_commit(root)
    if not COMMIT.fullmatch(commit):
        commit = 'unknown'
    short = commit if commit == 'unknown' else commit[:8] + ('-dirty' if commit.endswith('-dirty') else '')
    write_if_changed(root / GENERATED[1],
                     '// FILE IS GENERATED BY Makefile\n'
                     f'public let gitHash = "{commit}"\n'
                     f'public let gitShortHash = "{short}"\n')


def write_if_changed(path, text):
    # An unchanged file keeps its mtime, so SwiftPM does not rebuild Common for it.
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == '--git-only':
        print(git_commit(Path(sys.argv[2])))
    elif len(sys.argv) == 2:
        generate(Path.cwd(), sys.argv[1])
    else:
        sys.exit('usage: source_commit.py <version> | --git-only <worktree>')
